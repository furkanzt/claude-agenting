#!/usr/bin/env python3
"""Regenerate the BDD scenario coverage matrix + index from features/*.feature.

Each scenario carries tags and a "# Backed by: <ref>" comment (or @gap). This
tool parses those and emits a human index + a full coverage matrix. Run it
whenever the feature files change so the matrix never drifts from the specs.
Deterministic, no network.

NOTE: the summary line format `**N scenarios** — **N ARMED**` is parsed by the
meta-guard's freshness test (test_catalogue_integrity.py) — change both or
neither.
"""
from __future__ import annotations

import glob
import os
import re

# ── EDIT ME per project ──────────────────────────────────────────────────────
# Repo root, assuming this file sits at <root>/scripts/quality/.
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FEATURES_DIR = "features"
MATRIX_PATH = os.path.join("docs", "scenarios", "coverage-matrix.md")
INDEX_PATH = "Scenarios.md"
# Feature files to skip in counts (e.g. a step-def harness self-test).
EXCLUDE_FILES: set[str] = set()
# Optional one-line description per feature file, shown in the index.
DESCRIPTIONS: dict[str, str] = {}
# Name of the meta-guard file, referenced in the matrix header prose.
META_GUARD = "tests/test_catalogue_integrity.py"
REGEN_CMD = "python3 scripts/quality/build_coverage_matrix.py"
# ─────────────────────────────────────────────────────────────────────────────

SCEN_RE = re.compile(r"^\s*(Scenario(?: Outline)?):\s*(.+?)\s*$")
TAG_RE = re.compile(r"^\s*@[\w:-]")
BACKED_RE = re.compile(r"#\s*Backed by:\s*(.+?)\s*$")
STEP_RE = re.compile(r"^\s*(Given|When|Then|And|But|Examples|Feature|Background)\b")


def parse_feature(path: str):
    lines = open(path, encoding="utf-8").read().splitlines()
    feature_title = os.path.basename(path)
    for ln in lines:
        m = re.match(r"^\s*Feature:\s*(.+?)\s*$", ln)
        if m:
            feature_title = m.group(1)
            break

    scenarios = []
    for i, ln in enumerate(lines):
        m = SCEN_RE.match(ln)
        if not m:
            continue
        title = m.group(2)
        tags: list[str] = []
        backed_parts: list[str] = []
        # Walk back over the contiguous tag/comment/blank block above,
        # AGGREGATING every "# Backed by:" line (stacked citations are all
        # kept — recording only the nearest would silently drop proofs).
        j = i - 1
        while j >= 0 and (i - j) <= 8:
            prev = lines[j]
            if STEP_RE.match(prev) or SCEN_RE.match(prev):
                break
            if TAG_RE.match(prev):
                tags = re.findall(r"@[\w:-]+", prev) + tags
            b = BACKED_RE.search(prev)
            if b:
                backed_parts.insert(0, b.group(1))
            j -= 1
        seen: list[str] = []
        for part in backed_parts:
            if part not in seen:
                seen.append(part)
        backed = ", ".join(seen) if seen else None
        is_gap = (
            "@gap" in tags
            or backed is None
            or backed.strip().lower().startswith("@gap")
            or backed.strip().lower() in {"gap", "(gap)"}
        )
        scenarios.append(
            {
                "title": title,
                "tags": [t for t in tags if t != "@gap"],
                "backed": None if is_gap else backed,
                "status": "GAP" if is_gap else "ARMED",
            }
        )
    return feature_title, scenarios


def main() -> int:
    files = sorted(
        f
        for f in glob.glob(os.path.join(ROOT, FEATURES_DIR, "*.feature"))
        if os.path.basename(f) not in EXCLUDE_FILES
    )

    per_file = []
    grand_total = grand_armed = grand_gap = 0
    for path in files:
        name = os.path.basename(path)
        title, scenarios = parse_feature(path)
        armed = sum(1 for s in scenarios if s["status"] == "ARMED")
        gap = sum(1 for s in scenarios if s["status"] == "GAP")
        grand_total += len(scenarios)
        grand_armed += armed
        grand_gap += gap
        per_file.append((name, title, scenarios, armed, gap))

    # ---- coverage matrix --------------------------------------------------
    matrix_abs = os.path.join(ROOT, MATRIX_PATH)
    os.makedirs(os.path.dirname(matrix_abs), exist_ok=True)
    mx = ["# BDD Coverage Matrix\n"]
    mx.append(
        f"> Generated by `{REGEN_CMD}` from `{FEATURES_DIR}/*.feature`. "
        "Do not hand-edit — re-run the script.\n"
    )
    mx.append(
        f"**{grand_total} scenarios** — **{grand_armed} ARMED** · **{grand_gap} GAP** "
        "(needs a test; only allowed with @wip). ARMED = the cited test EXISTS, "
        f"machine-verified by `{META_GUARD}` (file + function checked in CI); "
        "whether it SUFFICES is guarded by adversarial audits and mutation "
        "spot-checks, not this matrix.\n"
    )
    mx.append("| Domain | ARMED | GAP | Total |\n|---|--:|--:|--:|")
    for name, _title, _sc, armed, gap in per_file:
        mx.append(f"| `{name}` | {armed} | {gap} | {armed + gap} |")
    mx.append(f"| **TOTAL** | **{grand_armed}** | **{grand_gap}** | **{grand_total}** |\n")

    for name, title, scenarios, armed, gap in per_file:
        mx.append(f"\n## {name} — {title}\n")
        mx.append("| Scenario | Tags | Backed by | Status |\n|---|---|---|---|")
        for s in scenarios:
            tags = " ".join(s["tags"]) or "—"
            backed = s["backed"] if s["status"] == "ARMED" else "—"
            badge = "✅ ARMED" if s["status"] == "ARMED" else "🔴 GAP"
            title_cell = s["title"].replace("|", "\\|")
            backed_cell = (backed or "—").replace("|", "\\|")
            mx.append(f"| {title_cell} | {tags} | `{backed_cell}` | {badge} |")

    mx.append("\n## Priority gaps to close (the TDD backlog)\n")
    for name, title, scenarios, armed, gap in sorted(per_file, key=lambda r: -r[4]):
        gaps = [s for s in scenarios if s["status"] == "GAP"]
        if not gaps:
            continue
        mx.append(f"\n### `{name}` — {len(gaps)} gap(s)")
        for s in gaps:
            mx.append(f"- {s['title']}")

    open(matrix_abs, "w", encoding="utf-8").write("\n".join(mx) + "\n")

    # ---- root index --------------------------------------------------------
    ix = ["# Scenarios — the executable BDD catalogue\n"]
    ix.append(
        f"Index to `{FEATURES_DIR}/*.feature`, this project's executable "
        "behaviour catalogue, governed by [TDD.md](TDD.md) and [BDD.md](BDD.md).\n"
    )
    ix.append(
        f"**{grand_total} scenarios** across {len(per_file)} domains — "
        f"**{grand_armed} ARMED**, **{grand_gap} GAP**. Full breakdown: "
        f"[{MATRIX_PATH}]({MATRIX_PATH}).\n"
    )
    ix.append("| Feature | Scenarios | ARMED | GAP | What it pins |\n|---|--:|--:|--:|---|")
    for name, _title, scenarios, armed, gap in per_file:
        desc = DESCRIPTIONS.get(name, "")
        ix.append(
            f"| [`{name}`]({FEATURES_DIR}/{name}) | {len(scenarios)} | {armed} | {gap} | {desc} |"
        )
    ix.append(
        "\n## Conventions\n\n"
        "- **`# Backed by:`** — a comment above each scenario naming the test "
        "that proves it. `@gap` (with `@wip` while developing) means no test "
        "yet — that is the TDD backlog.\n"
        f"- **Regenerate this file + the matrix** — `{REGEN_CMD}`.\n"
    )
    open(os.path.join(ROOT, INDEX_PATH), "w", encoding="utf-8").write("\n".join(ix) + "\n")

    print(
        f"Wrote {INDEX_PATH} + {MATRIX_PATH} — "
        f"{grand_total} scenarios ({grand_armed} ARMED, {grand_gap} GAP)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
